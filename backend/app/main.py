"""FastAPI application entry point for Campus Resource Hub."""

import logging
from contextlib import asynccontextmanager

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from prometheus_fastapi_instrumentator import Instrumentator
from sqlalchemy import text

from app.config import get_settings
from app.database import engine
from app.routes import resources, reservations, maintenance, dashboard

settings = get_settings()

logging.basicConfig(
    level=getattr(logging, settings.log_level.upper(), logging.INFO),
    format="%(asctime)s %(levelname)s %(name)s: %(message)s",
)
logger = logging.getLogger(__name__)


@asynccontextmanager
async def lifespan(app: FastAPI):
    logger.info("Campus Resource Hub starting up...")
    yield
    logger.info("Campus Resource Hub shutting down...")
    await engine.dispose()


app = FastAPI(
    title="Campus Resource Hub API",
    description=(
        "A campus facility booking and maintenance management system. "
        "Students and staff can discover campus facilities, reserve resources, "
        "and report maintenance issues."
    ),
    version=settings.app_version,
    lifespan=lifespan,
    docs_url="/docs",
    redoc_url="/redoc",
)

